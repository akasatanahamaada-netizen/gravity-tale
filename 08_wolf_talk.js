/* ============================================================================
   ステージ：第一話 ── 狼  id = 'wolf_talk'
   種類：story　狼に話しかける。「危険を告げるか」で分岐（flags.warnedHood）
   担当：
   ----------------------------------------------------------------------------
   分岐の作り方：npc の choices に選択肢を並べ、set でフラグを立てる。
   ここで立てた flags.warnedHood は、後の「おばあさんの家」で使われます。
   ========================================================================== */

GT.defineStage('wolf_talk', {
  platforms:[
    {page:'left', x:120, y:360, w:120, h:20, kind:'ledge'},
    {page:'right',x:660, y:330, w:130, h:20, kind:'ledge'},
  ],
  boxes:[], enemies:[],
});

GT.registerScene({
  id:'wolf_talk', type:'story', stage:'wolf_talk', label:'第一話 ── 狼',
  intro:{s:'',c:'narr',t:'茂みの向こうから、狼が現れた。赤ずきんのそばに立っている。狼に話しかけてみよう。'},
  npcs:[
    { who:'hood', name:'赤ずきん', page:'right', x:560 },   // その場にいる（会話相手は狼）
    { who:'wolf', name:'狼', page:'right', x:700, lines:[
      {s:'狼',c:'wolf',t:'こんにちは、赤ずきんちゃん。'},
      {s:'赤ずきん',c:'hood',t:'こんにちは。'},
      {s:'狼',c:'wolf',t:'どこへ行くんだい？'},
      {s:'赤ずきん',c:'hood',t:'おばあちゃんのところ。ガレットとバターの壺を届けに。'},
      {s:'狼',c:'wolf',t:'おばあさんは、どこに住んでいるの？'},
      {s:'赤ずきん',c:'hood',t:'この先の、風車小屋を過ぎた、村で一番端のお家よ。'},
      {s:'狼',c:'wolf',t:'僕もそっちへ行くところなんだ。君はその道を、僕はあっちの道を。どっちが早いか競争しよう。'},
      {s:'',c:'narr',t:'狼は、少年の視線を避けるようにして、脇道へ入っていく。'},
      {s:'',c:'narr',t:'少年は強い違和感を覚えた。赤ずきんに、伝えるべきか。'},
    ], choices:[
      { label:'狼はあやしい、と赤ずきんに伝える', set:()=>{GT.flags.warnedHood=true;}, after:[
        {s:'赤ずきん',c:'hood',t:'……ただの競争よ？　狼さん、いつも優しいもの。'},
        {s:'',c:'narr',t:'少年がなおも訴える。'},
        {s:'赤ずきん',c:'hood',t:'……分かった。じゃあ、急ぎましょう。'},
      ]},
      { label:'何も言わない', set:()=>{GT.flags.warnedHood=false;}, after:[
        {s:'',c:'narr',t:'少年は口をつぐんだ。赤ずきんは、鼻歌まじりに歩いていく。'},
      ]},
    ], onEnd:()=>{ GT.fillPage('wolf', GT.flags.warnedHood
        ?'——少年は違和感に気づき、赤ずきんに危険を告げた。'
        :'——狼は、脇道へ消えていった。'); } },
  ],
});
